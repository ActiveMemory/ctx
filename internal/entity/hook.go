// HookInput represents the JSON payload that hook runners (Claude Code,
// Codex, and Antigravity) send to hook commands via stdin.
//
// Fields:
//   - SessionID: Session identifier (normalized across tools)
//   - ToolInput: Tool-specific fields from the invocation
//   - Prompt: Raw prompt text (normalized across tools)
//   - ToolName: Tool name from the invocation (e.g. "Bash", "run_command")
//   - CWD: Current working directory from invocation
//   - ConversationID: Antigravity conversation identifier
//   - WorkspacePaths: Antigravity workspace paths
//   - TranscriptPath: Antigravity transcript JSONL path
//   - ModelName: Antigravity model name
//   - LastUserInput: Antigravity user input text
//   - ToolCall: Antigravity tool call payload
//   - ToolError: Antigravity error string from failed tool execution
type HookInput struct {
	SessionID      string      `json:"session_id"`
	ToolInput      ToolInput   `json:"tool_input"`
	Prompt         string      `json:"prompt"`
	ToolName       string      `json:"tool_name,omitempty"`
	CWD            string      `json:"cwd,omitempty"`
	ConversationID string      `json:"conversationId,omitempty"`
	WorkspacePaths []string    `json:"workspacePaths,omitempty"`
	TranscriptPath string      `json:"transcriptPath,omitempty"`
	ModelName      string      `json:"modelName,omitempty"`
	LastUserInput  string      `json:"lastUserInput,omitempty"`
	ToolCall       AgyToolCall `json:"toolCall,omitempty"`
	ToolError      string      `json:"error,omitempty"`
}

// Agy returns true if the hook input was generated by Antigravity
// (detected via ConversationID or CTX_HOOK_TOOL=agy).
//
// Returns:
//   - bool: true when running under Antigravity
func (h HookInput) Agy() bool {
	if h.ConversationID != "" {
		return true
	}
	tool := os.Getenv(agy.EnvHookTool)
	return tool == hook.ToolAgy || tool == hook.ToolAntigravity
}

// ToolInput contains the tool-specific fields from a hook invocation.
// For shell hooks, Command holds the shell command. For file hooks,
// FilePath holds the target path.
type ToolInput struct {
	Command  string `json:"command"`
	FilePath string `json:"file_path,omitempty"`
}

// AgyToolCall represents an Antigravity tool invocation envelope.
//
// Fields:
//   - Name: Tool name (e.g. "run_command", "edit_file", "write_file")
//   - Args: Arguments passed to the tool
type AgyToolCall struct {
	Name string      `json:"name"`
	Args AgyToolArgs `json:"args"`
}

// AgyToolArgs represents arguments passed to Antigravity tools.
//
// Fields:
//   - CommandLine: Shell command for run_command
//   - Path: File path for file tools
//   - FilePath: Alternative file path argument
//   - Command: Alternative command argument
type AgyToolArgs struct {
	CommandLine string `json:"CommandLine,omitempty"`
	Path        string `json:"Path,omitempty"`
	FilePath    string `json:"file_path,omitempty"`
	Command     string `json:"command,omitempty"`
}

// BlockResponse is the JSON output for blocked commands.
//
// Fields:
//   - Decision: "block" or "allow"
//   - Reason: Human-readable explanation
type BlockResponse struct {
	Decision string `json:"decision"`
	Reason   string `json:"reason"`
}

// Stats holds the fields written to the per-session stats JSONL file.
//
// Fields:
//   - Timestamp: ISO 8601 timestamp
//   - Prompt: Prompt counter within the session
//   - Tokens: Total token count at this point
//   - Pct: Percentage of context window used
//   - WindowSize: Context window size in tokens
//   - Model: Model ID (omitted if unknown)
//   - Event: Event type that triggered this entry
type Stats struct {
	Timestamp  string `json:"ts"`
	Prompt     int    `json:"prompt"`
	Tokens     int    `json:"tokens"`
	Pct        int    `json:"pct"`
	WindowSize int    `json:"window"`
	Model      string `json:"model,omitempty"`
	Event      string `json:"event"`
}

// TokenInfo holds token usage and model information extracted from a
// session's JSONL file.
//
// Fields:
//   - Tokens: Total input tokens (input + cache_creation + cache_read)
//   - Model: Model ID from the last assistant message, or ""
type TokenInfo struct {
	Tokens int    // Total input tokens (input + cache_creation + cache_read)
	Model  string // Model ID from the last assistant message, or ""
}
